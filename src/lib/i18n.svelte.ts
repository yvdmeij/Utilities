const MESSAGES: Record<Lang, Messages> = { en, nb, nl };

/** Translate a key in the active language. Reads reactive state, so templates update on switch. */
export function t(
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const msg = MESSAGES[i18n.lang][key] ?? en[key];
  if (!params) return msg;
  return msg.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

