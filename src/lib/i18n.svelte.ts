const LANG_KEY = 'quietkit:lang';

function readLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === 'en' || stored === 'nb' || stored === 'nl') return stored;
  } catch {
    // Storage unavailable (private mode) — fall back to English.
  }
  return 'en';
}

export const i18n = $state<{ lang: Lang }>({ lang: readLang() });

export function setLang(lang: Lang): void {
  i18n.lang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Ignore storage failures — the choice just won't persist.
  }
  document.documentElement.lang = lang;
}

